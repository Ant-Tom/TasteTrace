package com.tastetrace.review;

import com.tastetrace.config.AppProperties;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

/**
 * Stores review photos as plain files under one directory (a Docker volume in production).
 * Keys look like {@code reviews/<reviewId>/<uuid>} and map 1:1 to relative paths,
 * so photos migrated from the old S3 bucket keep working without database changes.
 */
@Component
public class PhotoStorage {

    private final Path root;

    public PhotoStorage(AppProperties appProperties) {
        this.root = Path.of(appProperties.storage().photosDir()).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot create photo directory " + root, e);
        }
    }

    public void put(String key, byte[] bytes) throws IOException {
        Path target = resolve(key);
        Files.createDirectories(target.getParent());
        // Write to a temp file and rename, so a crash never leaves a half-written photo behind.
        Path temp = Files.createTempFile(target.getParent(), ".upload-", ".tmp");
        try {
            Files.write(temp, bytes);
            Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } finally {
            Files.deleteIfExists(temp);
        }
    }

    public InputStream open(String key) throws IOException {
        return Files.newInputStream(resolve(key));
    }

    public boolean exists(String key) {
        return Files.isRegularFile(resolve(key));
    }

    /** Keys are generated by the app, but the check keeps a bad key from escaping the photo directory. */
    Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new IllegalArgumentException("Invalid photo key: " + key);
        }
        return path;
    }
}
